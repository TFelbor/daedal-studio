"""The credential surface of `server/config_store.py`, asserted rather than described.

CLAUDE.md's *never touch these unless the issue explicitly says so* list named the
whole file, and a file cannot tell a credential from a feature flag that happens to be
declared beside one. #168 added `ALLOW_PROMPT_JOBS` — non-secret, absent from
`SUBPROCESS_ENV_KEYS`, no relation to `DS_API_TOKEN` — and tripped a blocking review
about credentials over a change that added none, while the thing genuinely worth an
issue about that key was what it *does*: re-open the path that bills EUR 0,32 a
generation. #175 narrowed the rule to the surface that is actually load-bearing and
pointed it here, so the claim is a failing test rather than a paragraph nobody re-reads.

This file is the narrowed rule's enforceable half, and only the half that was missing.
The invariants that already have a home stay in it:

* `DS_API_TOKEN` is not a `CONFIG_KEYS` entry — `tests/test_api_auth.py`,
  `tests/test_api_token.py`.
* The subprocess allowlist is an allowlist, and each entry names its reader —
  `tests/test_subprocess_env.py`.
* A printer credential is bound to the host it was saved for, and the HTTP surface
  refuses an internal key — `tests/test_credential_host_binding.py`,
  `tests/test_config_api.py`.

What nothing asserted is the **inventory**: a new `secret: True` key could appear, or an
existing one lose its flag, and every test above would still pass, because each of them
tests a mechanism rather than the set of secrets the mechanism protects.

Everything here is static — no database, no network, no server process.
"""

from pathlib import Path

import pytest

from server.config_store import (
    CONFIG_KEY_PATH_ENV,
    CONFIG_KEYS,
    INTERNAL_CONFIG_KEYS,
    PRINTER_CREDENTIAL_HOSTS,
    SUBPROCESS_ENV_KEYS,
    default_config_key_path,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
CONTRACT = REPO_ROOT / "CLAUDE.md"

#: Every `secret: True` key the store holds, and why this server is allowed to hold it.
#:
#: Adding a key here is the change the contract asks for an issue about: it is one more
#: credential on a host whose `POST /config` is protected by a single shared token, and
#: one more value that a dump of `app_config` reduces to the Fernet key on disk. The
#: test below fails until the new key is listed, so the decision is taken in a diff
#: somebody reads rather than in a dict literal somebody scrolls past.
EXPECTED_SECRET_KEYS = {
    "HF_TOKEN": (
        "HuggingFace's gated FLUX download. The one secret with a legitimate reason to "
        "reach a subprocess, and `SUBPROCESS_ENV_KEYS` names the reader."
    ),
    "OCTOPRINT_API_KEY": (
        "A printer credential this server sends outbound; bound to OCTOPRINT_URL's "
        "host at the moment it is written."
    ),
    "MOONRAKER_API_KEY": (
        "A printer credential this server sends outbound; bound to MOONRAKER_URL's "
        "host at the moment it is written."
    ),
    "BAMBU_CODE": (
        "The LAN access code, which is a printer credential this server sends "
        "outbound; bound to BAMBU_IP at the moment it is written."
    ),
    "VAPID_PRIVATE_KEY": (
        "Generated by server/push.py, never typed and never returned. Internal, "
        "because a writable one is a server that can be made to sign for somebody "
        "else's identity."
    ),
}

#: The secrets a launched subprocess may carry. Both are justified in
#: `SUBPROCESS_ENV_KEYS` itself; what this set adds is that the *secret* part of that
#: allowlist cannot grow silently. Every other credential reaches a child, if at all,
#: as the dispatch gate's firmware-resolved `DS_PRINTER_KEY`.
SECRETS_ALLOWED_INTO_A_SUBPROCESS = {"HF_TOKEN", "OCTOPRINT_API_KEY"}


def _secret_keys() -> set:
    return {key for key, meta in CONFIG_KEYS.items() if meta.get("secret")}


def test_the_secret_bearing_keys_are_a_closed_inventory():
    """A new credential, or a lost `secret: True`, fails here before it ships."""
    assert _secret_keys() == set(EXPECTED_SECRET_KEYS), (
        "The set of secrets this server holds changed. Adding one is a credential "
        "decision and needs the issue CLAUDE.md asks for; removing a `secret: True` "
        "flag unmasks the value in `GET /config`. Update EXPECTED_SECRET_KEYS with "
        "the reason once the decision is recorded."
    )


@pytest.mark.parametrize("key", sorted(CONFIG_KEYS))
def test_every_key_declares_whether_it_is_a_secret(key):
    """An omitted flag is a silent downgrade, not a default.

    `secret` and `required` are read with `.get()` in several places, so a key that
    simply does not mention `secret` is treated as public by the masking in
    `GET /config` and by `/config/{key}/reveal`. That is the one way a credential can
    join the store without the inventory above noticing, and it is a typo away.
    """
    meta = CONFIG_KEYS[key]
    assert isinstance(meta.get("secret"), bool), f"{key} does not declare `secret`"
    assert isinstance(meta.get("required"), bool), f"{key} does not declare `required`"


def test_a_secret_leaves_this_process_only_where_it_is_expected():
    """The secret half of the subprocess allowlist is exactly two keys."""
    assert _secret_keys() & set(SUBPROCESS_ENV_KEYS) == SECRETS_ALLOWED_INTO_A_SUBPROCESS


def test_an_internal_key_is_never_handed_to_a_subprocess():
    """Internal keys are the ones no person types; no child process reads one either.

    `VAPID_PRIVATE_KEY` is the case that matters — it is generated here and signs for
    this server's identity — and the three `*_HOST` keys are the record of a binding,
    meaningless outside the process that checks it.
    """
    assert not (INTERNAL_CONFIG_KEYS & set(SUBPROCESS_ENV_KEYS))


@pytest.mark.parametrize("credential", sorted(PRINTER_CREDENTIAL_HOSTS))
def test_a_bound_printer_credential_is_a_secret_with_an_internal_host_key(credential):
    """The binding only means anything while both halves keep their declared shape.

    A bound credential that stopped being `secret: True` would be readable through
    `GET /config`; a `*_HOST` key that stopped being internal would be writable through
    `POST /config`, which is the confused deputy the binding exists to close, reopened
    by one more request.
    """
    host_key, address_key = PRINTER_CREDENTIAL_HOSTS[credential]
    assert CONFIG_KEYS[credential]["secret"] is True
    assert host_key in INTERNAL_CONFIG_KEYS
    assert address_key in CONFIG_KEYS
    assert CONFIG_KEYS[address_key]["secret"] is False


def test_the_fernet_key_is_not_a_stored_value():
    """The key that decrypts the store cannot be a row in the store it decrypts.

    It is a path on the host, `$DS_CONFIG_KEY_PATH` defaulting to
    `~/.ds-mvp/.config_key`, and that is what makes a dump of `app_config` ciphertext.
    A `CONFIG_KEYS` entry naming it would put the location — and, through
    `POST /config`, the choice of location — behind the same endpoint whose values it
    protects. The default also stays out of the checkout, where a stray `git add`
    reaches it.
    """
    assert CONFIG_KEY_PATH_ENV not in CONFIG_KEYS
    assert not [key for key in CONFIG_KEYS if "CONFIG_KEY" in key]
    assert REPO_ROOT not in Path(default_config_key_path()).resolve().parents


def test_the_contract_points_at_these_guards():
    """CLAUDE.md promises this file exists; a rename must not make that a dead pointer.

    The narrowed rule is only safe because it names an enforced set instead of a whole
    file. If the pointer rots, the rule reads as a licence to edit the credential
    surface freely, which is the opposite of what #175 decided.
    """
    contract = CONTRACT.read_text(encoding="utf-8")
    assert "tests/test_config_store_guards.py" in contract
    for symbol in ("SUBPROCESS_ENV_KEYS", "INTERNAL_CONFIG_KEYS", "DS_API_TOKEN"):
        assert symbol in contract, f"the contract no longer names {symbol}"
