"""Web push for the one moment this product has to interrupt someone.

A print runs for hours. The person who started it is not watching it, which is the
entire point of the dispatch gate and of `awaiting_verdict`: the printer says it
finished, and only a person can say whether the part actually came off the bed. That
question reaches nobody if it only ever appears on a page nobody has open.

So: one notification, when a job reaches `awaiting_verdict`, on the devices that asked
for one.

**Why a reconciler and not a hook.** Three code paths move a job into
`awaiting_verdict` — `print_dispatch` and `_run_pipeline` in `server/app.py`, and
`OctoPrintCollector._on_event`, which runs in whichever process claimed the job and
never touches the broadcaster. Hooking all three means three places to forget, in two
processes, one of which is not this one. Reading the state instead is one place, and
it is the same shape as `GET /feedback/pending`, which already asks the database the
same question.

**Why `push_sent` is a `job_event` and not a column.** It is the dedup key. A flag in
this process's memory would send a second notification after a restart, and a
`print_job` column would be a migration for a signal that is exactly what `job_event`
exists to absorb. The check is "does this job have a `push_sent` event"; the write
happens once, and everything after it is bookkeeping.

**The backlog guard.** The first tick after this ships would otherwise notify for every
job that has been sitting in `awaiting_verdict` since before push existed — which on a
pilot database is every finished print anyone forgot to answer. `PUSH_MAX_AGE_S`
bounds it: a job is notified only while its `completed_at` is recent. A server that
restarts inside that window still delivers; a backlog from last month never does.

**No user model.** `server/auth.py` is one shared secret and there is no per-user
anything, so a notification goes to every device that subscribed. That is honest for a
two-person pilot and it is why `push_subscription` has no user column — writing one
would claim an identity nothing in this product establishes.

**The dependency.** `pywebpush` (MPL-2.0) with `py-vapid` (MPL-2.0) and `http-ece`
(MIT), recorded in `pythonsrc/licence_policy.REVIEWED_WEAK_COPYLEFT` and in
`THIRD-PARTY-NOTICES.md` § 1. The alternative was ~150 lines of RFC 8291 on the
`cryptography` already in the tree; it was refused because the failure mode of a
hand-rolled ECDH-and-AES-GCM payload is a push service answering 400 on a real device
and nothing at all in CI. `webpush_async` runs on `aiohttp`, which the api-server image
already carries, so the send does not block the event loop.
"""

from __future__ import annotations

import asyncio
import base64
import json
import logging
import os
from datetime import datetime, timedelta, timezone
from typing import Any, Callable, Optional

from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

logger = logging.getLogger(__name__)

# ── Configuration ────────────────────────────────────────────────────────────

#: The stored VAPID keypair. Both are `CONFIG_KEYS` marked internal, so `POST /config`
#: refuses them and the Settings page never lists them: they are generated by this
#: server and there is nothing for a person to type. The public half leaves through
#: `GET /push/vapid-public-key`, which is what the browser needs to subscribe; the
#: private half never leaves at all.
VAPID_PUBLIC_KEY = "VAPID_PUBLIC_KEY"
VAPID_PRIVATE_KEY = "VAPID_PRIVATE_KEY"

#: The `sub` claim of the VAPID JWT. RFC 8292 wants a `mailto:` or `https:` URI a push
#: service can use to reach whoever is sending — it is a contact address, not a
#: credential, which is why it is the one push key a person may set.
VAPID_SUBJECT = "VAPID_SUBJECT"

#: Used when `VAPID_SUBJECT` is unset. A real address belongs in the store, not in the
#: repository, and no push service this product targets refuses a placeholder — but a
#: *missing* `sub` is refused by all of them, so there has to be a default.
DEFAULT_VAPID_SUBJECT = "mailto:push@daedal.studio"

#: How often the reconciler asks the database. Thirty seconds: the question is "has a
#: print finished", and a print takes hours — a tighter loop buys nothing and a looser
#: one makes the notification arrive after the person has already wandered past the
#: printer. `0` disables the loop, the way `$DS_DB_HEALTH_INTERVAL_S` does.
PUSH_INTERVAL_ENV = "DS_PUSH_INTERVAL_S"
DEFAULT_PUSH_INTERVAL_S = 30.0

#: How recently a job must have reached `awaiting_verdict` to be worth a notification.
#: One hour. See **The backlog guard** above.
PUSH_MAX_AGE_ENV = "DS_PUSH_MAX_AGE_S"
DEFAULT_PUSH_MAX_AGE_S = 3600.0

#: Seconds a single push service POST may take. They are third-party endpoints on the
#: public internet and one that hangs must not hold the tick.
PUSH_TIMEOUT_S = 10.0

#: How long a push service should hold the notification for a device that is offline.
#: Twelve hours: after that the answer to "did your print work" is stale enough that an
#: interruption is not a favour.
PUSH_TTL_S = 12 * 60 * 60

#: The job event that both records the send and prevents the next one.
PUSH_SENT = "push_sent"


def _env_float(name: str, default: float) -> float:
    """A float from the environment, falling back on anything unreadable."""
    raw = os.environ.get(name)
    if raw is None or not raw.strip():
        return default
    try:
        return float(raw)
    except ValueError:
        logger.warning("%s is not a number (%r); using %s", name, raw, default)
        return default


def push_interval_s() -> Optional[float]:
    """Seconds between reconciler ticks, or None when the loop is switched off."""
    interval = _env_float(PUSH_INTERVAL_ENV, DEFAULT_PUSH_INTERVAL_S)
    return interval if interval > 0 else None


def push_max_age_s() -> float:
    """How old a finished job may be and still be worth a notification."""
    return _env_float(PUSH_MAX_AGE_ENV, DEFAULT_PUSH_MAX_AGE_S)


# ── The keypair ──────────────────────────────────────────────────────────────


def _b64url(raw: bytes) -> str:
    """Base64url with the padding stripped — the only spelling web push uses."""
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def generate_vapid_keypair() -> tuple[str, str]:
    """A fresh P-256 keypair, in the two shapes web push asks for.

    Returns:
        `(public, private)`. The public half is the uncompressed point
        (`0x04 || X || Y`, 65 bytes) base64url-encoded, which is exactly what
        `pushManager.subscribe({applicationServerKey})` takes. The private half is the
        32-byte scalar, base64url-encoded — `py_vapid.Vapid.from_string` reads that
        form, and it stores as one short line of text rather than as a PEM block.

    Generated with `cryptography`, which is already in the tree and is what py-vapid
    would use anyway; the point is that nothing here needs a file on disk.
    """
    private = ec.generate_private_key(ec.SECP256R1())
    scalar = private.private_numbers().private_value.to_bytes(32, "big")
    point = private.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
    return _b64url(point), _b64url(scalar)


def ensure_vapid_keys(store) -> tuple[str, str]:
    """The stored keypair, generating one on first use.

    **Both halves or neither.** A public key without its private key is a browser
    subscribing to an identity this server cannot sign for, and a private key without
    its public key is a server nobody can subscribe to — so a half-written pair is
    replaced rather than completed. The cost of regenerating is that existing
    subscriptions stop working, which is the correct outcome: they were made against a
    key that is gone.

    Args:
        store: The encrypted config store (`server.config_store`).

    Returns:
        `(public, private)`, both base64url.
    """
    public = store.get(VAPID_PUBLIC_KEY)
    private = store.get(VAPID_PRIVATE_KEY)
    if public and private:
        return public, private

    if public or private:
        logger.warning(
            "Only half a VAPID keypair is stored; generating a new one. Devices "
            "subscribed against the old key will have to subscribe again."
        )
    public, private = generate_vapid_keypair()
    store.set(VAPID_PUBLIC_KEY, public)
    store.set(VAPID_PRIVATE_KEY, private)
    logger.info("Generated a VAPID keypair for web push")
    return public, private


def vapid_subject(store) -> str:
    """The `sub` claim: what a push service would use to contact this sender."""
    return (store.get(VAPID_SUBJECT) or "").strip() or DEFAULT_VAPID_SUBJECT


# ── The notification ─────────────────────────────────────────────────────────

#: Where a tap lands. `/dashboard/<job_id>` is the SPA's own route for a job (see
#: `web/src/App.tsx`); `/jobs/<id>` is the *API*, and sending the worker there would
#: open a JSON document in the installed app.
JOB_PATH = "/dashboard/"


def notification_payload(job) -> dict[str, Any]:
    """What the service worker is handed for one finished print.

    The body is the job's own label — `print_job.prompt`, which is the typed line for a
    prompt job and `spec_label(spec)` for a spec job, so a notification says which
    thing finished rather than "a print finished".

    `tag` is the job id so a second delivery for the same job replaces the first in the
    tray instead of stacking beside it. That is belt and braces: the reconciler already
    sends once, and this is what makes a duplicate visible as one notification rather
    than as two.
    """
    label = (getattr(job, "prompt", "") or "").strip()
    return {
        "title": "Print finished — did it work?",
        "body": label or "Your print has finished. Tell us how it came out.",
        "url": f"{JOB_PATH}{job.job_id}",
        "job_id": job.job_id,
        "tag": f"job-{job.job_id}",
    }


# ── Sending ──────────────────────────────────────────────────────────────────

#: The push service's two ways of saying "this subscription is gone for good". Anything
#: else — a 429, a 502, a timeout — is this delivery failing, not the device.
GONE_STATUSES = (404, 410)


def _subscription_info(row: dict) -> dict:
    """A stored row in the shape `pywebpush` expects."""
    return {
        "endpoint": row["endpoint"],
        "keys": {"p256dh": row["p256dh"], "auth": row["auth"]},
    }


async def send_to_subscription(
    row: dict,
    payload: dict,
    private_key: str,
    subject: str,
    sender: Optional[Callable] = None,
) -> tuple[bool, Optional[int]]:
    """Deliver one notification to one device.

    Args:
        row: A `push_subscription` row.
        payload: What `notification_payload` built.
        private_key: The base64url VAPID private key.
        subject: The `sub` claim.
        sender: `webpush_async`, injectable so the tests never open a socket.

    Returns:
        `(delivered, status)`. `status` is the HTTP status when the push service gave
        one — which is what tells a dead subscription from a bad afternoon.
    """
    if sender is None:  # pragma: no cover - exercised by the live path only
        from pywebpush import webpush_async

        sender = webpush_async

    from pywebpush import WebPushException

    try:
        await sender(
            subscription_info=_subscription_info(row),
            data=json.dumps(payload),
            vapid_private_key=private_key,
            vapid_claims={"sub": subject},
            ttl=PUSH_TTL_S,
            timeout=PUSH_TIMEOUT_S,
        )
        return True, None
    except WebPushException as exc:
        status = getattr(getattr(exc, "response", None), "status", None)
        if status is None:
            status = getattr(getattr(exc, "response", None), "status_code", None)
        logger.warning("Push to %s failed (%s): %s", row["endpoint"][:60], status, exc)
        return False, status
    except Exception as exc:  # noqa: BLE001 — one dead endpoint is not the tick's problem
        logger.warning("Push to %s failed: %s", row["endpoint"][:60], exc)
        return False, None


async def notify_job(db, store, job, sender: Optional[Callable] = None) -> dict[str, Any]:
    """Send one job's notification to every subscribed device, and record it.

    The `push_sent` event is written **after** the sends, with what happened in its
    detail. Writing it first would be the safer order against a crash mid-send, and it
    was rejected: the event is the only record this product keeps of a delivery, and an
    event that claims a send that never happened is worse than the one duplicate
    notification a crash between the two can cause.

    A job with **no subscriptions** is not recorded as sent. Nothing was delivered, and
    marking it would mean the first device to subscribe afterwards silently misses the
    job it subscribed for.

    Returns:
        `{"sent": n, "failed": n, "removed": [endpoint, ...], "recorded": bool}`.
    """
    rows = db.get_push_subscriptions()
    if not rows:
        logger.debug("Job %s is awaiting a verdict, but no device is subscribed", job.job_id)
        return {"sent": 0, "failed": 0, "removed": [], "recorded": False}

    payload = notification_payload(job)
    private = store.get(VAPID_PRIVATE_KEY)
    if not private:
        logger.error("No VAPID private key stored; cannot send push for job %s", job.job_id)
        return {"sent": 0, "failed": 0, "removed": [], "recorded": False}
    subject = vapid_subject(store)

    results = await asyncio.gather(
        *(send_to_subscription(row, payload, private, subject, sender) for row in rows)
    )

    sent = 0
    failed = 0
    removed: list[str] = []
    for row, (delivered, status) in zip(rows, results, strict=True):
        if delivered:
            sent += 1
            continue
        failed += 1
        if status in GONE_STATUSES:
            db.delete_push_subscription(row["endpoint"])
            removed.append(row["endpoint"])

    db.record_job_event(
        job.job_id,
        PUSH_SENT,
        detail={"sent": sent, "failed": failed, "removed": len(removed)},
    )
    logger.info(
        "Push for job %s: %d delivered, %d failed, %d subscription(s) forgotten",
        job.job_id, sent, failed, len(removed),
    )
    return {"sent": sent, "failed": failed, "removed": removed, "recorded": True}


def _completed_recently(job, max_age_s: float, now: Optional[datetime] = None) -> bool:
    """Whether a finished job is recent enough to interrupt someone about.

    A row with no `completed_at` is not notified. Every writer that sets
    `awaiting_verdict` sets it in the same call, so an empty one means a row from
    before that was true — which is exactly the backlog this guard is for.
    """
    completed = getattr(job, "completed_at", None)
    if completed is None:
        return False
    if completed.tzinfo is None:
        completed = completed.replace(tzinfo=timezone.utc)
    return (now or datetime.now(timezone.utc)) - completed <= timedelta(seconds=max_age_s)


async def reconcile_once(db, store, sender: Optional[Callable] = None) -> dict[str, Any]:
    """One tick: notify every job that has reached `awaiting_verdict` and not been told.

    Args:
        db: A `TelemetryDB`.
        store: The encrypted config store.
        sender: `webpush_async`, injectable for the tests.

    Returns:
        `{"considered": n, "notified": [job_id, ...], "skipped_old": n,
        "already_sent": n}` — enough for a test to assert on and for a log line to be
        worth reading.
    """
    max_age = push_max_age_s()
    considered = db.get_jobs_awaiting_verdict(limit=50)
    notified: list[str] = []
    skipped_old = 0
    already_sent = 0

    for job in considered:
        if db.get_job_events(job.job_id, kind=PUSH_SENT):
            already_sent += 1
            continue
        if not _completed_recently(job, max_age):
            skipped_old += 1
            continue
        result = await notify_job(db, store, job, sender)
        if result["recorded"]:
            notified.append(job.job_id)

    return {
        "considered": len(considered),
        "notified": notified,
        "skipped_old": skipped_old,
        "already_sent": already_sent,
    }
